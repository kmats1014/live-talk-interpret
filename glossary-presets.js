/**
 * 日本語の音声認識 (Web Speech API) が同音異義語で誤変換しやすい教会用語を
 * 登録用語集の variants をもとに自動補正する関数
 */
export function normalizeChurchSpeechText(rawText, glossaryList) {
  if (!rawText) return '';
  let normalized = rawText;

  // 登録されている用語集の variants（誤変換パターン）を優先的に正規化
  for (const item of glossaryList) {
    if (!item.enabled || !Array.isArray(item.variants)) continue;
    for (const variant of item.variants) {
      if (variant && variant.trim().length > 0 && normalized.includes(variant)) {
        normalized = normalized.replaceAll(variant, item.ja);
      }
    }
  }

  // よくある文脈的な音声認識誤変換の補正（実地礼拝ログに基づくLDS教会用語・聖典名・聖餐の祈り含む）
  const contextualReplacements = [
    ['あがない', '贖い'],
    ['みことば', '御言葉'],
    ['しゅのいのり', '主の祈り'],
    ['アー麺', 'アーメン'],
    ['あーめん', 'アーメン'],
    ['ラーメン。', 'アーメン。'], // 祈りの末尾での典型的誤認識
    ['ハレル屋', 'ハレルヤ'],
    // 聖典・教会組織・決議表現
    ['興味と聖約', '教義と聖約'],
    ['興味 と 聖約', '教義と聖約'],
    ['講座人への手紙', 'コロサイ人への手紙'],
    ['口座人への手紙', 'コロサイ人への手紙'],
    ['諸モーション', 'モルモン書'],
    ['モールモンション', 'モルモン書'],
    ['モルモンション', 'モルモン書'],
    ['ステーク初期', 'ステーク書記'],
    ['ステップ初期', 'ステーク書記'],
    ['ワード初期', 'ワード書記'],
    ['真剣者', '神権者'],
    ['真権者', '神権者'],
    ['感謝の会員', '感謝の決議'],
    ['Cするように定義', '支持するように提議'],
    ['指示するように定義', '支持するように提議'],
    ['支持するように定義', '支持するように提議'],
    ['知恵のことま', '知恵の言葉'],
    ['占教師', '宣教師'],
    ['少女公開', '処女航海'],
    ['シャデラック', 'シャデラク'],
    ['2尺アベデナム', 'メシャク、アベデネゴ'],
    ['アベデナム', 'アベデネゴ'],
    // 聖餐の祈り・祈祷文脈の誤変換
    ['愛する店のお父様', '愛する天のお父様'],
    ['永遠の背中を', '永遠の御霊を'],
    ['香港する体の記念', '御子の体の記念'],
    ['いつも香港を覚えている', 'いつも御子を覚えている'],
    ['香港イエス', '御子イエス'],
    ['温厚イエス', '御子イエス'],
    ['キリストの家によって', 'キリストの御名によって'],
    ['祝福し極めて', '祝福し聖めて'],
  ];

  for (const [wrong, right] of contextualReplacements) {
    if (normalized.includes(wrong)) {
      normalized = normalized.replaceAll(wrong, right);
    }
  }

  return normalized;
}
